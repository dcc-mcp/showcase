'use strict';
const assert = require('node:assert/strict');
const {attach} = require('./publication_shell.js');
let listener, reloads=0;
const sent=[], printed=[], parent={postMessage:(data,origin)=>sent.push({data,origin})}, win={};
const config={onPrint:(...args)=>printed.push(args)};
const shell=attach(config,{window:win,parent,origin:'https://dcc-mcp.github.io',reload:()=>reloads++,listen:f=>listener=f});
listener({source:parent,origin:'https://dcc-mcp.github.io',data:{type:'showcase:reset'}});
assert.equal(reloads,0);
config.onPrint('RELIC_STATE {}');assert.equal(sent.length,0);
config.onPrint('RELIC_FRAME_READY {}');assert.equal(sent[0].data.state,'running');assert.equal(printed.length,2);
listener({source:{},origin:'https://dcc-mcp.github.io',data:{type:'showcase:reset'}});
listener({source:parent,origin:'https://evil.invalid',data:{type:'showcase:reset'}});
listener({source:parent,origin:'https://dcc-mcp.github.io',data:{type:'showcase:sound-on'}});
assert.equal(reloads,0);
listener({source:parent,origin:'https://dcc-mcp.github.io',data:{type:'showcase:reset'}});assert.equal(reloads,1);
shell.failed();assert.equal(sent[1].data.state,'error');
const solo={postMessage:()=>{throw new Error('Standalone must not message itself');}};
attach({}, {window:solo,parent:solo,origin:'https://dcc-mcp.github.io',reload:()=>{},listen:()=>{}}).failed();
console.log('Publication bridge: native readiness, trusted parent origin/source, reset isolation and failure reporting passed.');
